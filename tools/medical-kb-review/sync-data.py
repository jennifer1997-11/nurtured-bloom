"""
Medical KB Review Dashboard - Data Sync Script
Reads all approved sources, records, and source gaps from knowledge/medical/
and outputs data.js for the Review Dashboard.
"""
import os
import json
from pathlib import Path

WORKSPACE_ROOT = Path(__file__).resolve().parent.parent.parent
MEDICAL_DIR = WORKSPACE_ROOT / "knowledge" / "medical"
OUTPUT_FILE = Path(__file__).resolve().parent / "data.js"

def sync_data():
    sources_path = MEDICAL_DIR / "sources.json"
    records_dir = MEDICAL_DIR / "records"
    gaps_dir = MEDICAL_DIR / "source-gaps"
    
    # 1. Load Sources
    sources_data = {}
    if sources_path.exists():
        with open(sources_path, "r", encoding="utf-8") as f:
            sources_data = json.load(f)
            
    # 2. Load Records
    records_list = []
    unparseable_records = []
    if records_dir.exists():
        for filename in sorted(os.listdir(records_dir)):
            if filename.endswith(".json") and not filename.startswith("_"):
                file_path = records_dir / filename
                try:
                    with open(file_path, "r", encoding="utf-8") as f:
                        rec = json.load(f)
                        rec["_filename"] = filename
                        records_list.append(rec)
                except Exception as e:
                    unparseable_records.append({"filename": filename, "error": str(e)})

    # 3. Load Source Gaps
    gaps_list = []
    unparseable_gaps = []
    if gaps_dir.exists():
        for filename in sorted(os.listdir(gaps_dir)):
            if filename.endswith(".json") and not filename.startswith("_"):
                file_path = gaps_dir / filename
                try:
                    with open(file_path, "r", encoding="utf-8") as f:
                        gap = json.load(f)
                        gap["_filename"] = filename
                        gaps_list.append(gap)
                except Exception as e:
                    unparseable_gaps.append({"filename": filename, "error": str(e)})

    payload = {
        "sync_timestamp": "2026-08-19T15:52:00+08:00",
        "sources_registry": sources_data,
        "records": records_list,
        "source_gaps": gaps_list,
        "unparseable": {
            "records": unparseable_records,
            "gaps": unparseable_gaps
        }
    }
    
    js_content = f"// Auto-generated by sync-data.py - DO NOT EDIT MANUALLY\nwindow.MEDICAL_KB_DATA = {json.dumps(payload, ensure_ascii=False, indent=2)};\n"
    
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        f.write(js_content)
        
    print(f"Synced {len(records_list)} records, {len(gaps_list)} gaps, {len(sources_data.get('sources', []))} sources to data.js")
    if unparseable_records or unparseable_gaps:
        print(f"Warning: {len(unparseable_records)} unparseable records, {len(unparseable_gaps)} unparseable gaps")

if __name__ == "__main__":
    sync_data()
